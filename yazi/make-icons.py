#!/usr/bin/env python3
"""Regenerates the [icon] section of theme.toml: yazi's own icon table, with every icon
colour moved onto the dungeonOS palette (same mapping as ../signal/patch.py).

    python3 ~/Dotfiles/yazi/make-icons.py

Rerun after a yazi update if new file types show up in their stock colours.
"""
import os, re, shutil, sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "signal"))
from patch import map_rgb, hex_rgb, fmt   # noqa: E402

THEME = os.path.join(HERE, "theme.toml")
BEGIN, END = "# --- generated by make-icons.py: begin ---", "# --- generated by make-icons.py: end ---"

# yazi keeps its preset theme inside the binary; take the dark theme's [icon] section
data = open(shutil.which("yazi"), "rb").read().decode("utf-8", "replace")
start = data.index('\n[flavor]\ndark  = ""')            # start of the dark preset theme
icon_start = data.index("\n[icon]\n", start)
icon_end = data.index("\n# : }}}", icon_start)
section = data[icon_start + 1:icon_end].rstrip()

def recolour(m):
    return f'fg = "{fmt(*map_rgb(*hex_rgb(m.group(1))))}"'

section = re.sub(r'fg = "(#[0-9a-fA-F]{6})"', recolour, section)
# folders in the same brass as their names
section = re.sub(r'(\{ if = "dir(?: & hovered)?", text = "[^"]*", fg = )"[^"]*"', r'\1"#A88A5B"', section)

theme = open(THEME).read()
if BEGIN in theme:
    theme = theme[:theme.index(BEGIN)].rstrip() + "\n"
theme += f"\n{BEGIN}\n{section}\n{END}\n"
open(THEME, "w").write(theme)
print(f"wrote {section.count('fg = ')} icon colours to {THEME}")
